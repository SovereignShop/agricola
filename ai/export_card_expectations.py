"""Export a validated static two-player draft ranking for the browser/JVM bots."""
import argparse
import hashlib
import json
from pathlib import Path

def main():
    p=argparse.ArgumentParser();p.add_argument('experiment',type=Path);p.add_argument('output',type=Path)
    args=p.parse_args();report_path=args.experiment/'report.json';report=json.loads(report_path.read_text())
    if report['status']!='complete':p.error('Only a complete independent test can be exported')
    result=report['test'];gain=result['paired_vs_heuristic']
    if min(gain['score_gain_95_interval'][0],gain['margin_gain_95_interval'][0])<=0:p.error('Both independent-test improvement intervals must exclude zero')
    models=json.loads((args.experiment/'models.json').read_text());formula=result['selected'];model=models['models'][formula]
    if model['pairs']:p.error('This exporter supports static rankings only; conditional pairs need a separately tested runtime')
    values=model['main']
    if len(values)!=82:p.error('Expected the complete two-player card catalog')
    lines=[';; Generated by ai/export_card_expectations.py. Two-player drafts only.',
           ';; Policy-dependent dealt-card associations; not intrinsic card points.',
           '{:version 1 :players 2',f' :formula :{formula}',
           f' :rules-hash "{models["rules"]}"',
           f' :source-report-sha256 "{hashlib.sha256(report_path.read_bytes()).hexdigest()}"',
           f' :training-deals {report["dataset"]["training_deals"]}',
           f' :test-deals {gain["independent_deals"]}',
           f' :test-score-gain {gain["score_gain"]}',
           f' :test-margin-gain {gain["margin_gain"]}',
           ' :values {']
    for cid,value in sorted(values.items()):
        if not cid.startswith(':revised-base/'):p.error('Unexpected card ID')
        lines.append(f'  {cid} {float(value)!r}')
    lines.append('}}\n');args.output.parent.mkdir(parents=True,exist_ok=True)
    args.output.write_text('\n'.join(lines));print(f'Exported {len(values)} {formula} values to {args.output}')

if __name__=='__main__':main()
