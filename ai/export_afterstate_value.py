"""Export only a completed, independently improved random-hand AND draft policy."""
import argparse
import hashlib
import json
from pathlib import Path


def edn(value):
    if value is None: return 'nil'
    if isinstance(value, bool): return 'true' if value else 'false'
    if isinstance(value, str): return json.dumps(value, ensure_ascii=False)
    if isinstance(value, dict): return '{' + '\n '.join(edn(k) + ' ' + edn(v) for k, v in value.items()) + '}'
    if isinstance(value, list): return '[' + ' '.join(map(edn, value)) + ']'
    return repr(value)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('experiment', type=Path)
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    experiment = args.experiment
    for folder in [experiment, experiment / 'draft-test', experiment / 'test-ablation']:
        if json.loads((folder / 'status.json').read_text())['status'] != 'complete':
            parser.error('Random-hand, draft and ablation tests must all be complete')
    report = json.loads((experiment / 'report.json').read_text())
    draft = json.loads((experiment / 'draft-test/report.json').read_text())
    if report['smoke_only']: parser.error('A smoke model cannot be exported')
    selected = report['selected']
    for gain in [report['test'][selected]['paired_vs_heuristic'], draft['paired']]:
        if min(gain['score_gain_95_interval'][0], gain['margin_gain_95_interval'][0]) <= 0:
            parser.error('Independent score and margin gains must exclude zero in both game modes')
    if selected != draft['selected']: parser.error('Draft test selected a different model')
    kind, blend = selected.split('-')
    model = json.loads((experiment / f'{kind}.json').read_text())
    root = Path(__file__).resolve().parents[1]
    sources = ['agricola/afterstate_value.clj', 'agricola/bot.clj', 'agricola/simulation.clj']
    fingerprint = hashlib.sha256(''.join((root / 'src/clj' / f).read_text() for f in sources).encode()).hexdigest()
    if fingerprint != model['source']: parser.error('Current evaluation source differs from the tested model')
    model.update(players=2, variant='cards', blend=float(blend), margin=1.,
                 provenance={'experiment': str(experiment), 'selected': selected,
                             'random_gain': report['test'][selected]['paired_vs_heuristic'], 'draft_gain': draft['paired'],
                             'report_sha256': hashlib.sha256((experiment / 'report.json').read_bytes()).hexdigest(),
                             'draft_report_sha256': hashlib.sha256((experiment / 'draft-test/report.json').read_bytes()).hexdigest()})
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(';; Generated by ai/export_afterstate_value.py. Two-player card games only.\n' + edn(model) + '\n')
    print(f'Exported {selected}: {len(model["weights"])} features to {args.output}')


if __name__ == '__main__': main()
