"""EDN macros are compile-time inputs: invalidate CLJS caches when they change."""
import hashlib
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[1]
# Compile the existing JVM policy for the browser without changing its training
# fingerprint. This generated adapter has one source of truth, not a second AI.
bot_source = (ROOT / "src/clj/agricola/bot.clj").read_text()
assert bot_source.count("catch clojure.lang.ExceptionInfo") == 1
assert bot_source.count("^java.util.Random") == 1
bot_source = bot_source.replace("catch clojure.lang.ExceptionInfo", "catch :default").replace("^java.util.Random ", "")
bot_target = ROOT / "src/cljs/agricola/bot.cljs"
bot_target.parent.mkdir(parents=True, exist_ok=True)
bot_target.write_text(";; GENERATED by scripts/build_browser.py from src/clj/agricola/bot.clj. Do not edit.\n" + bot_source)
# Keep the learned evaluator identical to the tested JVM implementation. Only
# pure evaluation functions enter the browser, not recording/training I/O.
value_source = (ROOT / "src/clj/agricola/afterstate_value.clj").read_text()
value_core = value_source[value_source.index("(defn flag "):value_source.index("(defn extract ")]
value_core += value_source[value_source.index("(defn predict "):value_source.index("(defn run-game ")]
assert value_core.count("^java.util.Random") == 1
value_core = value_core.replace("^java.util.Random ", "")
value_header = ''';; GENERATED by scripts/build_browser.py. Do not edit.
(ns agricola.afterstate-value
  (:require [agricola.bot :as bot] [agricola.engine :as a]
            [agricola.card-game :as g] [agricola.card-rules :as cards]))
'''
(ROOT / "src/cljs/agricola/afterstate_value.cljs").write_text(value_header + value_core)
subprocess.run(["python3", "scripts/build_discord.py"], cwd=ROOT, check=True)
# rules-hash is a macro too. A source change must refresh the embedded identity.
data = sorted((ROOT / "resources/agricola").glob("*.edn")) + sorted((ROOT / "src/main/cljc/agricola").glob("*.cljc"))
data += sorted((ROOT / "resources/eurozone").glob("*.edn"))
data += [ROOT / "build.cljs.edn", ROOT / "build.bot.cljs.edn", ROOT / "resources/externs/eurozone.js"]
digest = hashlib.sha256()
for path in data:
    digest.update(path.name.encode())
    digest.update(b"\0")
    digest.update(path.read_bytes())
stamp = ROOT / "resources/public/js/.game-data.sha256"
fingerprint = digest.hexdigest()
if not stamp.exists() or stamp.read_text() != fingerprint:
    for directory in ["out", "bot-out"]:
        cache = ROOT / "resources/public/js" / directory
        if cache.exists():
            shutil.rmtree(cache)
    print("Game compile-time inputs changed: rebuilding browser definitions", flush=True)
subprocess.run(["clojure", "-M:cljs:browser-build"], cwd=ROOT, check=True)
stamp.parent.mkdir(parents=True, exist_ok=True)
stamp.write_text(fingerprint)
