(require '[clojure.string :as str] '[clojure.data.json :as json]
         '[eurozone.store :as store] '[agricola.card-game :as g] '[agricola.card-rules :as c] '[agricola.engine :as a])
(let [ids (str/split (str/trim (with-out-str (load-file "test/eurozone/tabletop_browser_fixture.clj"))) #",")
      s (store/make-store (System/getenv "EUROZONE_DATA")) token (apply str (repeat 64 "a"))
      fresh (-> (g/initialize (a/new-game ["Ada" "Ben"] (vec (mapcat identity a/stages)) 0))
                (assoc-in [:players 0 :hand] {:minor [:catalog/original-base-i-95-fish-trap] :occupation [(c/id :a116)]})
                (update-in [:players 0] a/gain {:wood 10 :food 10}))
      minor (:id (store/transact! s token {:event :create :mode :local :name "Ada" :names ["Ada" "Ben"] :setup {:mode :random}}))
      payment (:id (store/transact! s token {:event :create :mode :local :name "Ada" :names ["Ada" "Ben"] :setup {:mode :random}}))
      scholar (:id (store/transact! s token {:event :create :mode :local :name "Ada" :names ["Ada" "Ben"] :setup {:mode :random}}))
      pending (-> fresh (assoc :phase :preparation)
                  (assoc-in [:players 0 :house] :stone)
                  (assoc-in [:players 0 :occupations] [(c/id :b097)])
                  (g/queue-front [(g/task 0 (c/id :b097) {:op :scholar :optional? true} {})]) g/drain)
      draft (:id (store/transact! s token {:event :create :mode :online :name "Ada" :expected-players 2 :setup {:mode :draw :extra 2}}))]
  (store/transact! s (apply str (repeat 64 "b")) {:event :join :id draft :revision 0 :name "Ben"})
  (store/transact! s token {:event :start :id draft :revision 1})
  (store/save! s (swap! (:rooms s) #(-> % (assoc-in [minor :state] fresh) (assoc-in [scholar :state] pending)
                      (assoc-in [payment :state] (-> fresh (assoc-in [:players 0 :hand :minor] [(c/id :a004)]) (assoc-in [:players 0 :goods :grain] 1))))))
  (println (json/write-str {:occupation (first ids) :major (nth ids 3) :upgrade (nth ids 4) :minor minor :payment payment :scholar scholar :draft draft})))
