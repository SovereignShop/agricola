(require '[eurozone.store :as store] '[agricola.engine :as a] '[clojure.string :as str] '[clojure.set :as set]
         '[agricola.card-game :as g] '[agricola.card-rules :as c])
(def names ["Ada" "Ben" "Cara" "Dan"])
(defn fresh [] (g/initialize (a/new-game names (vec (mapcat identity a/stages)) 0)))
(defn own [state code]
  (update-in state [:players 0 (if (= :occupation (:kind (c/card (c/id code)))) :occupations :minors)] conj (c/id code)))
(defn hand [state code] (update-in state [:players 0 :hand (:kind (c/card (c/id code)))] (fnil conj []) (c/id code)))
(defn boundary [cells] (set (map key (filter #(= 1 (val %)) (frequencies (mapcat a/edges cells))))))
(def mixed {:type :field :crop :grain :count 3 :under-crops {:vegetable 1}})
(let [s (store/make-store (System/getenv "EUROZONE_DATA")) token (apply str (repeat 64 "a"))
      reclamation (-> (fresh) (own :a017) (assoc-in [:players 0 :fences] (boundary [0 1]))
                      (update :active conj :sheep) (assoc-in [:piles :sheep] {:sheep 3})
                      (g/command 0 {:type :action :space :sheep}))
      silage (-> (fresh) (own :a084) (assoc :phase :return-home)
                 (assoc-in [:players 0 :fences] (boundary [0 1]))
                 (assoc-in [:players 0 :farm 2] (assoc mixed :count 1))
                 (assoc-in [:players 0 :farm 3] {:type :field :count 0})
                 (update-in [:players 0] a/gain {:sheep 2})
                 (g/queue-front [(g/event :return-home 0)]) g/drain)
      full (-> (fresh) (own :a134) (own :b098)
               (assoc-in [:players 0 :fences] (set/union (boundary [0]) (boundary [1 2])))
               (update-in [:players 0] a/gain {:sheep 2 :boar 1}))
      oriental (-> (fresh) (hand :a060) (assoc-in [:players 0 :improvements] #{:hearth-4})
                   (update :available-improvements disj :hearth-4))
      winnowing (-> (fresh) (own :a060) (own :a061) (update-in [:players 0] a/gain {:grain 1})
                    (g/queue-front [(g/event :after-field-phase 0)]) g/drain)
      heresy (-> (fresh) (hand :a113)
                 (assoc-in [:players 0 :farm 0] (dissoc mixed :under-crops))
                 (assoc-in [:players 0 :farm 1] (dissoc mixed :under-crops)))
      knife (-> (fresh) (hand :a007) (update-in [:players 0] a/gain {:wood 1})
                (assoc-in [:players 0 :farm 0] mixed) (assoc-in [:players 0 :farm 1] mixed)
                (g/play-card 0 (c/id :a007) 0 {}) g/drain)
      freshman (-> (fresh) (own :a097) (hand :a116) (update :active conj :sow-bake))
      ids (mapv (fn [state]
                  (let [id (:id (store/transact! s token {:event :create :mode :local :name "Ada" :names names
                                                         :title "Artifex harvest" :setup {:mode :random}}))]
                    (store/save! s (swap! (:rooms s) assoc-in [id :state] state)) id))
                [reclamation silage full oriental winnowing heresy knife freshman])]
  (println (str/join "," ids)))
